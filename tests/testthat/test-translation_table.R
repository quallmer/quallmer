test_that("translations are coded tables with a text schema and retained inputs", {
  mock_translation_chat(function(text) paste("translated", text))
  input <- c(a = "one", b = "two")
  out <- qlm_translate(input, "openai/test", instructions = "Keep the register.")
  expect_s3_class(out, "qlm_coded")
  expect_s3_class(out, "data.frame")
  expect_false(inherits(out, "corpus"))
  expect_named(out, c(".id", "translation", ".error"))
  expect_identical(out$.id, names(input))
  expect_identical(out$translation, c("translated one", "translated two"))
  expect_identical(inputs(out), input)
  expect_named(codebook(out)$schema@properties, "translation")
  expect_match(codebook(out)$instructions, "Keep the register.")
  expect_identical(qlm_failures(out)$.id, character())
  expect_output(print(out), "qlm_translation")
  path <- tempfile(fileext = ".rds")
  saveRDS(out, path)
  expect_identical(readRDS(path), out)
})

test_that("table row selection, column selection and edits keep provenance aligned", {
  mock_translation_chat()
  out <- qlm_translate(c(a = "one", b = "two"), "openai/test")
  subset <- out[c(2, 1), ]
  expect_equal(translation_provenance(subset)$source_text, c("two", "one"))
  expect_identical(inputs(subset), c(b = "two", a = "one"))
  expect_identical(names(out), c(".id", "translation", ".error"))
  expect_false(inherits(out["translation"], "qlm_coded"))
  expect_false(inherits(out[c(".id", ".error")], "qlm_translation"))
  expect_named(out[c(".id", "translation")], c(".id", "translation"))
  expect_s3_class(out[c(".id", ".error")], "qlm_coded")
  expect_error(out[c(1, 1), ], "unique")
  subset$.id <- c("x", "y")
  expect_equal(translation_provenance(subset)$.id, c("x", "y"))
  expect_identical(names(inputs(subset)), c("x", "y"))
  out$translation[1] <- "edited"
  expect_equal(translation_provenance(out)$status, c("edited", "ok"))
  expect_equal(translation_provenance(out)$output_hash[1], translation_hash("edited"))
  out[2, "translation"] <- NA_character_
  expect_equal(translation_provenance(out)$status, c("edited", "failed"))
  expect_equal(qlm_failures(out)$.id, "b")
  expect_match(qlm_failures(out)$reason, "set to NA")
  expect_error(out[3, ] <- out[1, ], "unique|extended")
  expect_error(out$.id <- c("a", "a"), "unique")
  expect_error(out$translation <- 1:2, "character column")
  names(out)[2] <- "summary"
  expect_false(inherits(out, "qlm_translation"))
  expect_s3_class(out, "qlm_coded")
})

test_that("replacement by translated rows retains their actual provider provenance", {
  mock_translation_chat()
  out <- qlm_translate(c(a = "one", b = "two"), "openai/test")
  retry <- qlm_translate(c(b = "different source"), "openai/test", target_lang = "fr")
  out[2, ] <- retry
  expect_equal(out$translation, c("one", "different source"))
  expect_equal(translation_provenance(out)$status, c("ok", "ok"))
  expect_equal(translation_provenance(out)$target_lang, c("en", "fr"))
  expect_identical(inputs(out), c(a = "one", b = "different source"))
})

test_that("row binding combines translations and retains source inputs", {
  mock_translation_chat()
  a <- qlm_translate(c(a = "one"), "openai/test")
  b <- qlm_translate(c(b = "two"), "openai/test")
  out <- rbind(a, b)
  expect_equal(nrow(out), 2)
  expect_equal(translation_provenance(out)$source_text, c("one", "two"))
  expect_identical(inputs(out), c(a = "one", b = "two"))
  expect_error(rbind(a, a), "unique")
})

